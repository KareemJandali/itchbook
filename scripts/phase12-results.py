#!/usr/bin/env python3
"""phase12-results.py — generate docs/phase12-results.md from the artifact.

Generated, never typed, like every other results table in phases 9-12. `--check`
regenerates and diffs, so a stale table fails verify-local rather than waiting
for a reader to notice.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "validation", "replay-vs-live-2019-12-30.json")
DOC = os.path.join(ROOT, "docs", "phase12-results.md")
MODELS = ["naive", "optimistic", "mbo", "pessimistic"]


def n(v):
    return "—" if v is None else "{:,}".format(v)


def build():
    a = json.load(open(ART, encoding="utf-8"))
    b = a["lane_b"]
    la = a["lane_a"]
    cat = a["categories"]
    st = cat["structural_no_price_priority"]
    qa = cat["queue_approximation"]
    lat = cat["latency_model_shape"]

    L = []
    A = L.append
    A("# Phase 12 — Replay vs live. Results.")
    A("")
    A("*Generated by `scripts/phase12-results.py` from "
      "`validation/replay-vs-live-2019-12-30.json`. Every number here is in that "
      "artifact; none is typed.*")
    A("")
    A("The same strategy, the same %s messages of MSFT 2019-12-30, twice: once "
      "through the phase-6 queue backtester, once live through the phase-12.7 "
      "closed loop over real sockets." % n(a["window_messages"]))
    A("")

    A("## The two lanes")
    A("")
    A("| | orders | fills | shares |")
    A("|---|---:|---:|---:|")
    A("| **lane B — live** | %s | **%s** | %s |"
      % (n(b["orders"]), n(b["fills"]), n(b["shares"])))
    for k in MODELS:
        A("| lane A — `%s` | — | %s | %s |" % (k, n(la[k]["fills"]), n(la[k]["shares"])))
    A("")
    A("**Lane B fills less than every model the backtester offers.** The rest of "
      "this document is why, and every part of the gap is named.")
    A("")

    A("## Why there is no per-fill diff")
    A("")
    A("The plan says \"diff the fills\", which presumes a key pairing a lane-A "
      "fill with a lane-B fill. There is none, and the reason is a property of "
      "the system rather than of the tooling.")
    A("")
    A("**Lane B is not reproducible at the fill level.** `tools/exchange.cpp` "
      "polls TCP and then replays *one* message, so which historical message a "
      "strategy order lands after is a wall-clock race between two processes. "
      "Two runs of the same binaries on the same feed with the same flags gave "
      "**617 orders / 880 fills** and **634 / 847**. Phase 12.8 shows the same "
      "at scale: chain-A hops pool to n = 12,000 = 10 × 1,200 exactly, while "
      "every chain-B hop pools to n = 20,868 over those same ten runs — not "
      "divisible by ten.")
    A("")
    A("So the comparison is distributional. That is a weaker claim than the plan "
      "wanted and it is the true one.")
    A("")

    A("## Category: latency-model shape")
    A("")
    A("The plan says to set lane A's latency model to the measured hops from "
      "lane B. That instruction does not survive `tools/exchange.cpp:560`:")
    A("")
    A("```c")
    A("elapsed_replay = (wall_now - wall_start) * multiplier")
    A("```")
    A("")
    A("The live lane paces the tape by a multiplier, so its wall-clock latency "
      "is multiplied into feed time — at the 1000× every committed real-day run "
      "used, 13 µs of real order entry is 13 **milliseconds** of feed time. "
      "There is no single honest number. So lane A was swept instead:")
    A("")
    A("| latency ns | " + " | ".join("`%s`" % k for k in MODELS) + " |")
    A("|---:|" + "---:|" * len(MODELS))
    for s in lat["swept_ns"]:
        row = lat["fills_by_latency"][str(s)]
        A("| %s | %s |" % (n(s), " | ".join(n(row[k]) for k in MODELS)))
    A("")
    if lat["invariant"]:
        A("**Identical across five orders of magnitude.** The two lanes' latency "
          "models differ and it **cannot explain any disagreement below**: at "
          "this quoting rate even a millisecond is far under the interval "
          "between quotes. A confound that was worth worrying about, measured "
          "and eliminated rather than argued away.")
    A("")

    A("## Category: structural — lane B has no price-priority fill")
    A("")
    A("`include/itchbook/replay/split.hpp:84` is the whole classification table:")
    A("")
    A("```c")
    A("return type == 'E' ? Treatment::Aggressor : Treatment::State;")
    A("```")
    A("")
    A("Only `'E'` consults the matcher. A historical order that comes to rest "
      "at or through a strategy order is applied to the book and never checked "
      "against it. **Lane B therefore has no price-priority fill and no "
      "through-print fill at all** — not an approximation of them, none.")
    A("")
    A("Lane A labels every fill with the trigger that caused it "
      "(`SimFill::trigger`), so the size of the category is counted:")
    A("")
    A("| lane A model | fills | lock | through | structural | fills without them |")
    A("|---|---:|---:|---:|---:|---:|")
    for k in MODELS:
        s = st[k]
        A("| `%s` | %s | %s | %s | **%.1f%%** | %s |"
          % (k, n(la[k]["fills"]), n(s["lock"]), n(s["through"]),
             100.0 * s["share"], n(s["fills_without"])))
    A("| **lane B — live** | **%s** | **0** | **0** | — | **%s** |"
      % (n(b["fills"]), n(b["fills"])))
    A("")
    A("**Sixty per cent of `mbo`'s fills and sixty-nine per cent of "
      "`pessimistic`'s come from a path the live loop cannot take.**")
    A("")

    A("## Category: queue approximation")
    A("")
    A("| band over the four models | lane B | verdict |")
    A("|---|---:|---|")
    A("| as reported, `[%s, %s]` | %s | **%s** |"
      % (n(qa["band"][0]), n(qa["band"][1]), n(qa["lane_b"]),
         "inside" if qa["inside_band"] else "OUTSIDE"))
    A("| structural paths removed, `[%s, %s]` | %s | **%s** |"
      % (n(qa["band_without_structural"][0]), n(qa["band_without_structural"][1]),
         n(qa["lane_b"]),
         "inside" if qa["inside_band_without_structural"] else "OUTSIDE"))
    A("")
    A("This is the phase's result. **The backtester's band does not contain the "
      "live outcome** — and once the fill paths the live loop structurally "
      "lacks are removed, **it does**. The queue model is not what the gap was "
      "made of.")
    A("")

    A("## Category: inventory and marking")
    A("")
    A("Lane B's strategy sees its own orders on the feed — its own `'A'` came "
      "back for **%s of %s** orders — and can therefore quote off a book that "
      "contains them. Lane A's book is built from the feed alone and never "
      "contains its own orders. Quoting *below* the touch keeps this mostly "
      "inert: an order two ticks under the bid does not become the bid unless "
      "the market falls to it. It is named here because it is real, not because "
      "it was measured to matter."
      % (n(cat["inventory_and_marking"]["own_adds_seen_on_feed"]),
         n(cat["inventory_and_marking"]["orders"])))
    A("")

    A("## Caveats, stated up front as the plan requires")
    A("")
    for c in a["caveats"]:
        A("- %s" % c)
    A("")

    A("## What is not established")
    A("")
    A("**The strategies are mirrored, not shared.** "
      "`include/itchbook/sim/parity_maker.hpp` reproduces `tools/strategy.cpp`'s "
      "rule — buy-only, `bid − offset×tick`, the same crossed-book cap, never "
      "cancels — but they are two pieces of code. `tools/strategy.cpp` was left "
      "untouched deliberately: its behaviour is what 12.7 proved and 12.8 "
      "measured to the nanosecond, and editing it to meet the backtester would "
      "invalidate both.")
    A("")
    A("**The trigger counters still differ.** Lane B quotes every N messages "
      "that mutated its book; lane A counts every message it saw. The same "
      "stride therefore puts quotes at different instants. Calibrating the "
      "stride until the order counts matched would have hidden this behind a "
      "fitted constant; it is left visible.")
    A("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        if not os.path.exists(DOC):
            print("phase12-results: %s does not exist" % DOC)
            return 1
        if open(DOC, encoding="utf-8").read() != text:
            print("phase12-results: the committed document does not match the "
                  "artifact; re-run scripts/phase12-results.py")
            return 1
        print("phase12-results.md matches its artifact")
        return 0
    with open(DOC, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % DOC)
    return 0


if __name__ == "__main__":
    sys.exit(main())
