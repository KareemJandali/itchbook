#!/usr/bin/env python3
"""phase12-results.py — generate docs/phase12-results.md from the artifact.

Generated, never typed, like every other results table in phases 9-12. `--check`
regenerates and diffs, so a stale table fails verify-local rather than waiting
for a reader to notice.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "validation", "replay-vs-live-2019-12-30.json")
DOC = os.path.join(ROOT, "docs", "phase12-results.md")
MODELS = ["naive", "optimistic", "mbo", "pessimistic"]


def n(v):
    return "—" if v is None else "{:,}".format(v)


def build():
    a = json.load(open(ART, encoding="utf-8"))
    b = a["lane_b"]
    la = a["lane_a"]
    cat = a["categories"]
    st = cat["structural_no_price_priority"]
    qa = cat["queue_approximation"]
    lat = cat["latency_model_shape"]

    L = []
    A = L.append
    A("# Phase 12: replay versus live. Results.")
    A("")
    A("*Generated by `scripts/phase12-results.py` from "
      "`validation/replay-vs-live-2019-12-30.json`. Every number here is in that "
      "artifact; none is typed.*")
    A("")
    A("One strategy was run twice over the same %s messages of MSFT 2019-12-30. "
      "The first run went through the phase-6 queue backtester. The second ran "
      "live through the phase-12.7 closed loop, over real sockets."
      % n(a["window_messages"]))
    A("")

    A("## The two lanes")
    A("")
    A("| | orders | fills | shares |")
    A("|---|---:|---:|---:|")
    A("| **lane B — live** | %s | **%s** | %s |"
      % (n(b["orders"]), n(b["fills"]), n(b["shares"])))
    for k in MODELS:
        A("| lane A — `%s` | — | %s | %s |" % (k, n(la[k]["fills"]), n(la[k]["shares"])))
    A("")
    A("**Lane B fills less than every model the backtester offers.** What "
      "follows accounts for the difference, and each component of it is named.")
    A("")

    A("## Why there is no per-fill diff")
    A("")
    A("The plan says \"diff the fills\". That instruction presumes a key which "
      "pairs a lane-A fill with a lane-B fill. No such key exists, and the "
      "cause lies in the system itself.")
    A("")
    A("**Lane B is not reproducible at the fill level.** `tools/exchange.cpp` "
      "polls TCP and then replays *one* message. Which historical message a "
      "strategy order lands after is therefore settled by a wall-clock race "
      "between two processes. Two runs of the same binaries, on the same feed "
      "and with the same flags, gave **617 orders / 880 fills** and "
      "**634 / 847**. The same effect appears at scale in phase 12.8. Chain-A "
      "hops pool to n = 12,000 = 10 × 1,200 exactly, whereas every chain-B hop "
      "pools to n = 20,868 across those same ten runs, a figure that ten does "
      "not divide.")
    A("")
    A("The comparison is therefore distributional. A stronger claim was wanted "
      "by the plan, and this one is what the system supports.")
    A("")

    A("## Category: latency-model shape")
    A("")
    A("The plan says to set lane A's latency model to the measured hops from "
      "lane B. That instruction does not survive `tools/exchange.cpp:560`:")
    A("")
    A("```c")
    A("elapsed_replay = (wall_now - wall_start) * multiplier")
    A("```")
    A("")
    A("The live lane paces the tape by a multiplier, so its wall-clock latency "
      "is multiplied into feed time. At the 1000× that every committed real-day "
      "run used, 13 µs of real order entry becomes 13 **milliseconds** of feed "
      "time. No single honest number exists. Lane A was swept instead:")
    A("")
    A("| latency ns | " + " | ".join("`%s`" % k for k in MODELS) + " |")
    A("|---:|" + "---:|" * len(MODELS))
    for s in lat["swept_ns"]:
        row = lat["fills_by_latency"][str(s)]
        A("| %s | %s |" % (n(s), " | ".join(n(row[k]) for k in MODELS)))
    A("")
    if lat["invariant"]:
        A("**Identical across five orders of magnitude.** The two lanes use "
          "different latency models, and that difference **cannot explain any "
          "disagreement below**. At this quoting rate even a millisecond falls "
          "far under the interval between quotes. The confound deserved "
          "attention, and measurement removed it.")
    A("")

    A("## Category: structural — lane B has no price-priority fill")
    A("")
    A("`include/itchbook/replay/split.hpp:84` is the whole classification table:")
    A("")
    A("```c")
    A("return type == 'E' ? Treatment::Aggressor : Treatment::State;")
    A("```")
    A("")
    A("Only `'E'` consults the matcher. A historical order that comes to rest "
      "at or through a strategy order is applied to the book and never checked "
      "against it. **Lane B therefore has no price-priority fill and no "
      "through-print fill at all.** The count of each is zero.")
    A("")
    A("Lane A labels every fill with the trigger that caused it "
      "(`SimFill::trigger`), so the size of the category is counted:")
    A("")
    A("| lane A model | fills | lock | through | structural | fills without them |")
    A("|---|---:|---:|---:|---:|---:|")
    for k in MODELS:
        s = st[k]
        A("| `%s` | %s | %s | %s | **%.1f%%** | %s |"
          % (k, n(la[k]["fills"]), n(s["lock"]), n(s["through"]),
             100.0 * s["share"], n(s["fills_without"])))
    A("| **lane B — live** | **%s** | **0** | **0** | — | **%s** |"
      % (n(b["fills"]), n(b["fills"])))
    A("")
    A("**Sixty per cent of `mbo`'s fills and sixty-nine per cent of "
      "`pessimistic`'s come from a path the live loop cannot follow.**")
    A("")

    A("## Category: queue approximation")
    A("")
    A("| band over the four models | lane B | verdict |")
    A("|---|---:|---|")
    A("| as reported, `[%s, %s]` | %s | **%s** |"
      % (n(qa["band"][0]), n(qa["band"][1]), n(qa["lane_b"]),
         "inside" if qa["inside_band"] else "OUTSIDE"))
    A("| structural paths removed, `[%s, %s]` | %s | **%s** |"
      % (n(qa["band_without_structural"][0]), n(qa["band_without_structural"][1]),
         n(qa["lane_b"]),
         "inside" if qa["inside_band_without_structural"] else "OUTSIDE"))
    A("")
    A("This is the phase's result. **The backtester's band does not contain the "
      "live outcome.** Once the fill paths that the live loop structurally "
      "lacks are removed, **it does**. Very little of the difference is "
      "attributable to the queue model.")
    A("")

    A("## Category: inventory and marking")
    A("")
    A("Lane B's strategy sees its own orders on the feed. Its own `'A'` "
      "returned for **%s of %s** orders, so it can quote from a book that "
      "contains them. Lane A builds its book from the feed alone, and that book "
      "never holds its own orders. Because the strategy quotes *below* the "
      "touch, the effect stays mostly inert: an order two ticks under the bid "
      "becomes the bid only if the market falls to it. The category is listed "
      "here for completeness, and its size was left unmeasured."
      % (n(cat["inventory_and_marking"]["own_adds_seen_on_feed"]),
         n(cat["inventory_and_marking"]["orders"])))
    A("")

    A("## Caveats, stated first as the plan requires")
    A("")
    for c in a["caveats"]:
        A("- %s" % c)
    A("")

    A("## What is not established")
    A("")
    A("**The strategies are mirrored copies.** "
      "`include/itchbook/sim/parity_maker.hpp` reproduces the rule in "
      "`tools/strategy.cpp`: buy-only, `bid − offset×tick`, the same "
      "crossed-book cap, and no cancels. They remain two separate pieces of "
      "code. `tools/strategy.cpp` was deliberately left untouched, because its "
      "behaviour is what 12.7 proved and what 12.8 measured to the nanosecond. "
      "Editing it to suit the backtester would invalidate both.")
    A("")
    A("**The trigger counters still differ.** Lane B quotes every N messages "
      "that mutated its book, while lane A counts every message it saw. The "
      "same stride therefore places quotes at different instants. Calibrating "
      "the stride until the order counts agreed would have concealed the "
      "difference inside a fitted constant, so it remains visible.")
    A("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        if not os.path.exists(DOC):
            print("phase12-results: %s does not exist" % DOC)
            return 1
        if open(DOC, encoding="utf-8").read() != text:
            print("phase12-results: the committed document does not match the "
                  "artifact; re-run scripts/phase12-results.py")
            return 1
        print("phase12-results.md matches its artifact")
        return 0
    with open(DOC, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % DOC)
    return 0


if __name__ == "__main__":
    sys.exit(main())
